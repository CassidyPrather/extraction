#!/usr/bin/env python3
"""The voices on the radio dial (crates/extraction_core/src/music/stations.rs),
spoken by espeak-ng's own formant voices (never mbrola) and dressed as an AM
broadcast heard on a small set:

- assets/audio/radio/evacuation.ogg: the Quarantine Authority's automated
  loop from the Marrow valley office. The two-tone attention signal
  (853 Hz + 960 Hz together, 4 s), then the announcement, a little slowed.
- assets/audio/radio/numbers_voice.ogg: nobody's numbers station. A woman
  reads "Attention. Attention." and then groups of five figures, slowly.

Both are band-limited to what an AM broadcast carries (300 Hz to 3 kHz),
with a little mains hum, mastered to Ogg Vorbis, mono, 24 kHz. Both loop
cleanly: the filtering is circular and the hum a whole number of cycles
long. Also writes assets/audio/radio/manifest.json (file, text, voice
settings, length, licence).

    python3 scripts/radio_voices.py
"""
import json
import os
import random
import subprocess
import tempfile
import wave

import numpy as np

RATE = 24000
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "assets", "audio", "radio")
QUALITY = 2  # Vorbis -q:a

# The loop's eight lines, in order (Story's, held to docs/LORE.md): line 3
# is why Hana stayed (no dogs on the buses); line 6 was added after the
# machines came, on 2 November.
EVACUATION_TEXT = (
    "Attention. This valley is closed by order of the Quarantine Authority. "
    "Proceed to the south gate. Transport is provided. "
    "Take one bag for each person. Leave animals with water. "
    "Do not lock your door. Your property will be kept. "
    "You will return when the review is complete. "
    "Do not approach the machines. They are here to help. "
    "Report persons who remain to the gate. "
    "This message repeats."
)
EVACUATION_VOICE = {"voice": "en-gb", "speed": 140, "pitch": 38, "word_gap_10ms": 3}

NUMBERS_VOICE = {"voice": "en-gb+f3", "speed": 105, "pitch": 55, "word_gap_10ms": 25}
NUMBERS_SEED = 1215  # the station's spot on the dial
NUMBERS_GROUPS = 7
DIGITS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]

LICENCE = (
    "Generated by scripts/radio_voices.py with espeak-ng's built-in formant "
    "voices. espeak-ng is GPL-3.0-or-later; its spoken output is not covered "
    "by the program's licence. The project's own work."
)


def espeak(text, v):
    """Speaks `text`; returns float samples at RATE."""
    with tempfile.TemporaryDirectory() as d:
        wav = os.path.join(d, "v.wav")
        subprocess.run(
            ["espeak-ng", "-v", v["voice"], "-s", str(v["speed"]), "-p", str(v["pitch"]),
             "-g", str(v["word_gap_10ms"]), "-w", wav, text],
            check=True,
        )
        raw = subprocess.run(
            ["ffmpeg", "-v", "error", "-i", wav, "-ac", "1", "-ar", str(RATE),
             "-f", "f32le", "-"],
            check=True, capture_output=True,
        ).stdout
    x = np.frombuffer(raw, dtype=np.float32).astype(np.float64)
    # Trim espeak's own leading and trailing silence.
    on = np.flatnonzero(np.abs(x) > 1e-3)
    return x[on[0]:on[-1] + 1] if len(on) else x


def silence(seconds):
    return np.zeros(int(round(seconds * RATE)))


def attention_signal(seconds=4.0):
    """853 Hz and 960 Hz together, with soft edges."""
    t = np.arange(int(seconds * RATE)) / RATE
    x = 0.5 * (np.sin(2 * np.pi * 853 * t) + np.sin(2 * np.pi * 960 * t))
    edge = int(0.01 * RATE)
    ramp = np.linspace(0.0, 1.0, edge)
    x[:edge] *= ramp
    x[-edge:] *= ramp[::-1]
    return x


def level(x, rms=0.2):
    r = np.sqrt(np.mean(x ** 2))
    return x * (rms / r) if r > 0 else x


def broadcast(x, hum=0.012, seed=0):
    """An AM broadcast on a small set, circularly (so it loops): squashed
    loud, band-limited to 300 Hz-3 kHz, mains hum and a breath of hiss."""
    # Whole cycles of 50 Hz hum: a multiple of 480 samples.
    n = int(np.ceil(len(x) / 480) * 480)
    x = np.concatenate([x, np.zeros(n - len(x))])
    # Broadcast compression, crudely.
    x = np.tanh(2.0 * x / max(np.max(np.abs(x)), 1e-9)) / np.tanh(2.0)
    rng = np.random.default_rng(seed)
    x = x + 0.004 * rng.standard_normal(n)
    # Two poles each side, as magnitudes on the FFT (circular, so the
    # loop's end runs into its start).
    f = np.fft.rfftfreq(n, 1.0 / RATE)
    hp = (f / 300.0) ** 2 / np.sqrt(1 + (f / 300.0) ** 4)
    lp = 1.0 / np.sqrt(1 + (f / 3000.0) ** 4)
    x = np.fft.irfft(np.fft.rfft(x) * hp * lp, n)
    t = np.arange(n) / RATE
    x = x + hum * (np.sin(2 * np.pi * 50 * t) + 0.6 * np.sin(2 * np.pi * 100 * t)
                   + 0.3 * np.sin(2 * np.pi * 150 * t)) * np.max(np.abs(x))
    return x * (0.89 / np.max(np.abs(x)))


def write_ogg(x, name):
    path = os.path.join(OUT, name)
    with tempfile.TemporaryDirectory() as d:
        wav = os.path.join(d, "x.wav")
        with wave.open(wav, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", wav, "-ac", "1", "-ar", str(RATE),
             "-c:a", "libvorbis", "-q:a", str(QUALITY), path],
            check=True,
        )
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=nw=1:nk=1", path],
        check=True, capture_output=True, text=True,
    ).stdout
    return path, float(out)


def evacuation():
    voice = level(espeak(EVACUATION_TEXT, EVACUATION_VOICE))
    tone = level(attention_signal(), 0.15)
    x = np.concatenate([silence(0.6), tone, silence(1.2), voice, silence(3.0)])
    return broadcast(x, seed=1), EVACUATION_TEXT


def numbers_voice():
    rng = random.Random(NUMBERS_SEED)
    groups = ["".join(str(rng.randrange(10)) for _ in range(5)) for _ in range(NUMBERS_GROUPS)]
    head = level(espeak("Attention. Attention.", NUMBERS_VOICE))
    parts = [silence(0.8), head, silence(2.0)]
    for g in groups:
        spoken = ", ".join(DIGITS[int(c)] for c in g)
        parts += [level(espeak(spoken, NUMBERS_VOICE)), silence(1.6)]
    parts.append(silence(2.5))
    text = "Attention. Attention. " + " ".join(groups)
    return broadcast(np.concatenate(parts), hum=0.008, seed=2), text, groups


def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = []

    x, text = evacuation()
    path, secs = write_ogg(x, "evacuation.ogg")
    assert 35.0 <= secs <= 75.0, f"evacuation loop is {secs:.1f} s"
    manifest.append({
        "file": "evacuation.ogg",
        "text": text,
        "voice": dict(engine="espeak-ng", **EVACUATION_VOICE),
        "attention_signal": {"hz": [853, 960], "seconds": 4.0},
        "seconds": round(secs, 2),
        "loops": True,
        "license": LICENCE,
    })
    print(f"{path}: {secs:.1f} s")

    x, text, groups = numbers_voice()
    path, secs = write_ogg(x, "numbers_voice.ogg")
    manifest.append({
        "file": "numbers_voice.ogg",
        "text": text,
        "groups": groups,
        "voice": dict(engine="espeak-ng", **NUMBERS_VOICE),
        "seconds": round(secs, 2),
        "loops": True,
        "license": LICENCE,
    })
    print(f"{path}: {secs:.1f} s")

    common = {"sample_rate": RATE, "channels": 1, "codec": f"vorbis q{QUALITY}",
              "band_hz": [300, 3000], "made_by": "scripts/radio_voices.py"}
    with open(os.path.join(OUT, "manifest.json"), "w") as f:
        json.dump({**common, "files": manifest}, f, indent=2)
        f.write("\n")


if __name__ == "__main__":
    main()
